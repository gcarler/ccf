# Helper to create a FastAPI app with the router and overridden deps


def create_app(monkeypatch):
    app = FastAPI()
    app.include_router(cms.router)
    monkeypatch.setattr(cms, "_actor_sede_from_user", lambda db, current_user: None)

    # Override DB dependency to provide a dummy object
    # After router inclusion, replace each auth dependency (generated by require_module_access) with a stub that returns a dummy user.
    def _override_auth_deps(app_instance):
        from fastapi.routing import APIRoute

        class DummyUser:
            id = uuid.uuid4()
            role = "admin"
            rol_plataforma = None
            is_active = True
            permissions = {"cms:read": "allow", "cms:edit": "allow", "cms:manage": "allow"}

        for route in getattr(app_instance, "router").routes:
            if isinstance(route, APIRoute):
                for dep in getattr(route, "dependant").dependencies:
                    # The auth dependency is the inner function produced by require_permission
                    if callable(dep.call):

                        def _dummy_user():
                            return DummyUser()

                        app_instance.dependency_overrides[dep.call] = _dummy_user

    # Apply auth overrides
    _override_auth_deps(app)

    class DummyUserInstance:
        id = uuid.uuid4()
        role = "admin"
        rol_plataforma = None
        is_active = True
        permissions = {"cms:read": "allow", "cms:edit": "allow", "cms:manage": "allow"}

    app.dependency_overrides[get_current_user] = lambda: DummyUserInstance()

    class DummyDB:
        def query(self, *args, **kwargs):
            return self
        def filter(self, *args, **kwargs):
            return self
        def options(self, *args, **kwargs):
            return self
        def order_by(self, *args, **kwargs):
            return self
        def first(self, *args, **kwargs):
            return None
        def scalar(self, *args, **kwargs):
            return None
        def update(self, *args, **kwargs):
            return 0
        def all(self, *args, **kwargs):
            return []
        def add(self, *args, **kwargs):
            pass
        def commit(self, *args, **kwargs):
            pass
        def flush(self, *args, **kwargs):
            pass
        def refresh(self, obj, *args, **kwargs):
            if hasattr(obj, "id") and getattr(obj, "id") is None:
                obj.id = uuid.uuid4()
            if hasattr(obj, "created_at") and getattr(obj, "created_at") is None:
                obj.created_at = datetime.now(timezone.utc)
            if hasattr(obj, "updated_at") and getattr(obj, "updated_at") is None:
                obj.updated_at = datetime.now(timezone.utc)

    def get_db_override():
        return DummyDB()

    app.dependency_overrides[get_db] = get_db_override

    # Override permission dependency to bypass auth
    def require_module_access_override(*args, **kwargs):
        # Return a dummy user object with required attributes
        class DummyUser:
            id = uuid.uuid4()
            role = "admin"
            # emulate rol_plataforma for old compatibility
            rol_plataforma = None
            is_active = True
            permissions = {"cms:read": "allow", "cms:edit": "allow", "cms:manage": "allow"}

        return DummyUser()

    app.dependency_overrides[require_module_access] = require_module_access_override
    app.dependency_overrides[normalize_role] = lambda r: r.lower().strip() if r else ""

    from fastapi import Request
    from fastapi.responses import JSONResponse

    from backend.exceptions.cms import CmsError

    @app.exception_handler(CmsError)
    async def cms_exception_handler(request: Request, exc: CmsError):
        return JSONResponse(status_code=exc.status_code, content=exc.to_dict())

    return app


def test_slugify():
    # Basic slugify behavior
    assert cms._slugify("  Hello World  ") == "hello-world"
    # Removes illegal characters
    assert cms._slugify("My@Page!#") == "mypage"
    # Keeps underscores and slashes
    assert cms._slugify("/path/to/resource_") == "/path/to/resource_"


