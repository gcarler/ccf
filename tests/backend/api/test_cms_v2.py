def test_assert_role_fallback(monkeypatch):
    class DummyUser:
        role = ""

        class rol_plataforma:
            nombre = "Coordinador"

    # Should not raise for allowed role
    cms._assert_role(DummyUser(), {"coordinador"})
    # Disallowed role raises CmsPermissionError
    try:
        cms._assert_role(DummyUser(), {"admin"})
        assert False, "Expected CmsPermissionError"
    except CmsPermissionError as exc:
        assert exc.status_code == 403


def test_list_sites(monkeypatch):
    # Mock crud.list_cms_sites
    now = datetime.now(timezone.utc)
    mock_sites = [
        {
            "id": str(uuid.uuid4()),
            "site_key": "default",
            "name": "Default",
            "base_path": "/",
            "is_active": True,
            "created_at": now,
            "updated_at": now,
        }
    ]
    monkeypatch.setattr(
        backend_crud,
        "list_cms_sites",
        lambda db, only_active=False, sede_id=None: mock_sites,
    )

    app = create_app(monkeypatch)
    client = TestClient(app)
    response = client.get("/cms/v2/sites")
